"""Deployment of member tools (plan §8.4): ``docker-compose.tools.yml`` + per-tool env files.

Every approved or enabled tool gets one container:

* image pinned to the reviewed digest; only on the internal `tools` network
* no secrets except its own tool token; no access to MongoDB
* outbound traffic only through ``egress-proxy``, which allows the hosts in ``network_egress``
* read-only root, all capabilities dropped, non-root user, CPU / memory / PID limits

Use it on top of the main files:
    docker compose -f docker-compose.yml -f docker-compose.prod.yml -f docker-compose.tools.yml up -d
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from app.db.models import ToolDoc
from app.tools.tokens import tool_token

PROXY_HOST = "egress-proxy"
PROXY_PORT = 3128
TOOL_UID = "65532:65532"
_LOGGING = {"driver": "json-file", "options": {"max-size": "10m", "max-file": "3"}}
_HARDENING = {
    "read_only": True,
    "cap_drop": ["ALL"],
    "security_opt": ["no-new-privileges:true"],
}


def service_name(tool: str) -> str:
    return f"tool-{tool}"


def egress_rules(docs: list[ToolDoc]) -> dict[str, list[str]]:
    return {d.name: d.egress for d in docs}


def render(docs: list[ToolDoc], *, env_dir: str = "deploy/tools") -> dict[str, Any]:
    services: dict[str, Any] = {}
    for d in docs:
        res = d.resources or {}
        services[service_name(d.name)] = {
            "image": f"{d.image}@{d.image_digest}",
            "env_file": [f"{env_dir}/{d.name}.env"],
            "environment": {
                "DAYLINE_TOOL_NAME": d.name,
                "PORT": "8080",
                "NO_PROXY": "api,localhost,127.0.0.1",
                "no_proxy": "api,localhost,127.0.0.1",
                "NODE_USE_ENV_PROXY": "1",  # Node's built-in fetch ignores HTTPS_PROXY otherwise
            },
            "user": TOOL_UID,
            **_HARDENING,
            "tmpfs": ["/tmp:size=64m"],
            "cpus": res.get("cpus", 0.5),
            "mem_limit": res.get("memory", "256m"),
            "pids_limit": res.get("pids", 128),
            "networks": ["tools"],
            "depends_on": [PROXY_HOST],
            "restart": "unless-stopped",
            "logging": _LOGGING,
        }
    services[PROXY_HOST] = {
        "image": "${DAYLINE_REGISTRY:-}dayline-backend:${DAYLINE_IMAGE_TAG:-dev}",
        "command": ["python", "-m", "app.cli", "tools", "egress-proxy", "--port", str(PROXY_PORT)],
        # tools can reach this container: give it nothing from .env beyond what it needs
        "environment": {
            "DAYLINE_TOOLS_SECRET": "${DAYLINE_TOOLS_SECRET:?set DAYLINE_TOOLS_SECRET}",
            "DAYLINE_TOOLS_UPSTREAM_PROXY": "${DAYLINE_TOOLS_UPSTREAM_PROXY:-}",
            "DAYLINE_HOME": "/app",
            "DAYLINE_EGRESS_RULES": json.dumps(egress_rules(docs), sort_keys=True),
        },
        **_HARDENING,
        "tmpfs": ["/tmp"],
        "networks": ["tools", "egress"],
        "restart": "unless-stopped",
        "logging": _LOGGING,
        "healthcheck": {"disable": True},
    }
    return {
        "services": services,
        "networks": {"tools": {"internal": True}, "egress": {}},
    }


def env_file(secret: str, doc: ToolDoc) -> str:
    token = tool_token(secret, doc.name)
    proxy = f"http://{doc.name}:{token}@{PROXY_HOST}:{PROXY_PORT}"
    lines = [
        "# generated by `dl tools compose`; contains this tool's token - keep out of git",
        f"DAYLINE_TOOL_TOKEN={token}",
        f"HTTPS_PROXY={proxy}",
        f"HTTP_PROXY={proxy}",
        f"https_proxy={proxy}",
        f"http_proxy={proxy}",
    ]
    return "\n".join(lines) + "\n"


def write(
    docs: list[ToolDoc], *, secret: str, compose_path: Path, env_dir: Path, env_dir_ref: str
) -> list[Path]:
    env_dir.mkdir(parents=True, exist_ok=True)
    written = []
    keep = set()
    for d in docs:
        p = env_dir / f"{d.name}.env"
        p.write_text(env_file(secret, d), encoding="utf-8")
        p.chmod(0o600)
        keep.add(p.name)
        written.append(p)
    for stale in env_dir.glob("*.env"):
        if stale.name not in keep:
            stale.unlink()
    header = (
        "# Generated by `dl tools compose` from the approved / enabled member tools. Do not edit.\n"
        "# docker compose -f docker-compose.yml -f docker-compose.prod.yml -f docker-compose.tools.yml up -d\n"
    )
    compose_path.write_text(
        header + yaml.safe_dump(render(docs, env_dir=env_dir_ref), sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    written.append(compose_path)
    return written
