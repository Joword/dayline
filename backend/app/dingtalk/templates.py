"""DingTalk log template mapping (plan §10).

    config/templates/dingtalk_report.md     the company's log template (empty = not provided yet)
    config/templates/dingtalk_mapping.yaml  mapping, drafted by the template-mapper skill, confirmed by a person

* template empty  -> the whole report Markdown goes into the template's first field;
* template filled -> ``dl template map`` drafts a mapping; a person confirms it;
* at sync time    -> contents are rendered strictly from the mapping - no LLM;
* template edited -> its hash no longer matches ``template_hash``: sync stops and asks for remapping.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, Field, field_validator

from app.render.markdown import _item_line, _t, render_daily_report

# Every source a mapping may use. The template-mapper prompt shows exactly this list.
SOURCES: dict[str, str] = {
    "own_items[kind=done]": "已完成事项 / completed items",
    "own_items[kind=progress]": "进行中事项(含进度、预计完成) / in-progress items",
    "own_items[kind=blocker]": "阻塞和需要协调的事项 / blockers",
    "own_items[kind=plan]": "明日计划 / plan for tomorrow",
    "plan_check": "与上次计划的对照 / check against the last plan",
    "team_summary.summary": "团队整体情况(管理者) / team overview",
    "team_summary.highlights": "团队亮点(管理者) / team highlights",
    "team_summary.risks": "团队风险(管理者) / team risks",
    "team_summary.escalations": "需上级介入的事项(管理者) / escalations",
    "team_summary.missing": "未提交日报的成员(管理者) / members without a report",
}

Format = Literal["numbered_list", "bullet_list", "text"]


class FieldMap(BaseModel):
    dingtalk_field: str
    source: list[str]
    format: Format = "numbered_list"

    @field_validator("source", mode="before")
    @classmethod
    def _one_or_many(cls, v: Any) -> Any:
        return [v] if isinstance(v, str) else v

    @field_validator("source")
    @classmethod
    def _known(cls, v: list[str]) -> list[str]:
        unknown = [s for s in v if s not in SOURCES]
        if unknown:
            raise ValueError(f"unknown sources {unknown}; allowed: {sorted(SOURCES)}")
        return v


class TemplateMapping(BaseModel):
    template_hash: str
    fields: list[FieldMap] = Field(min_length=1)
    unmapped_policy: Literal["append_to_last", "drop"] = "append_to_last"


def template_hash(text: str) -> str:
    return hashlib.sha256(text.strip().encode("utf-8")).hexdigest()[:16]


def load_mapping(path: Path) -> TemplateMapping | None:
    if not path.is_file():
        return None
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or None
    return TemplateMapping.model_validate(data) if data else None


def save_mapping(path: Path, mapping: TemplateMapping) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Generated by `dl template map` and confirmed by a person. Re-run it when the template changes.\n"
    )
    path.write_text(
        header + yaml.safe_dump(mapping.model_dump(), allow_unicode=True, sort_keys=False), encoding="utf-8"
    )


class TemplateState(BaseModel):
    template_text: str
    empty: bool
    hash: str
    mapping: TemplateMapping | None
    stale: bool  # template changed since the mapping was confirmed

    @property
    def usable(self) -> bool:
        return self.empty or (self.mapping is not None and not self.stale)


def template_state(template_path: Path, mapping_path: Path) -> TemplateState:
    text = template_path.read_text(encoding="utf-8") if template_path.is_file() else ""
    h = template_hash(text)
    mapping = load_mapping(mapping_path)
    empty = not text.strip()
    return TemplateState(
        template_text=text,
        empty=empty,
        hash=h,
        mapping=mapping,
        stale=not empty and (mapping is None or mapping.template_hash != h),
    )


def template_field_names(text: str) -> list[str]:
    """Field names declared in the template file: Markdown headings or `字段:` lines."""
    names = []
    for line in text.splitlines():
        m = re.match(r"^\s*#{1,6}\s*(.+?)\s*$", line) or re.match(
            r"^\s*[-*]?\s*([^:#\-*][^:]{0,30})[::]\s*$", line
        )
        if m:
            names.append(m.group(1).strip())
    return names


# --- rendering (deterministic) -------------------------------------------------------------


def _source_lines(output: dict[str, Any], source: str, lang: str) -> list[str]:
    t = _t(lang)
    ts = output.get("team_summary") or {}
    names = ts.get("member_names") or {}
    if source.startswith("own_items[kind="):
        kind = source[len("own_items[kind=") : -1]
        return [_item_line(i, t) for i in output.get("own_items") or [] if i.get("kind") == kind]
    if source == "plan_check":
        return [
            f"{c.get('plan_text', '')}: {t['status'].get(c.get('status'), c.get('status'))}"
            for c in output.get("plan_check") or []
        ]
    if source == "team_summary.summary":
        return [ts["summary"]] if ts.get("summary") else []
    if source == "team_summary.highlights":
        return [
            h.get("text", "")
            + (f"({'、'.join(names.get(m, m) for m in h['members'])})" if h.get("members") else "")
            for h in ts.get("highlights") or []
        ]
    if source == "team_summary.risks":
        return [
            f"[{t['sev'].get(r.get('severity'), r.get('severity', ''))}] {r.get('text', '')}"
            for r in ts.get("risks") or []
        ]
    if source == "team_summary.escalations":
        return [
            e.get("text", "") + (f" — {e['need_from']}" if e.get("need_from") else "")
            for e in ts.get("escalations") or []
        ]
    if source == "team_summary.missing":
        missing = [m.get("name", m.get("id", "")) for m in ts.get("missing") or []]
        return ["、".join(missing)] if missing else []
    return []


def _format(lines: list[str], fmt: str) -> str:
    if fmt == "numbered_list":
        return "\n".join(f"{n}. {x}" for n, x in enumerate(lines, 1))
    if fmt == "bullet_list":
        return "\n".join(f"- {x}" for x in lines)
    return "\n".join(lines)


def render_contents(
    output: dict[str, Any],
    mapping: TemplateMapping | None,
    *,
    lang: str = "zh",
    default_field: str | None = None,
) -> list[dict[str, Any]]:
    """Report output -> DingTalk log `contents`. Without a mapping (empty template) the
    whole Markdown goes into `default_field` (the template's first field)."""

    def content(i: int, key: str, text: str) -> dict[str, Any]:
        return {"key": key, "sort": str(i), "type": "1", "content_type": "markdown", "content": text or "无"}

    if mapping is None:
        if not default_field:
            raise ValueError("no mapping and no default field")
        return [content(0, default_field, render_daily_report(output, lang))]
    rendered, covered = [], set()
    for i, f in enumerate(mapping.fields):
        lines = [line for s in f.source for line in _source_lines(output, s, lang)]
        covered.update(f.source)
        rendered.append([i, f.dingtalk_field, _format(lines, f.format)])
    if mapping.unmapped_policy == "append_to_last":
        extra = []
        for s in SOURCES:
            if s not in covered and (lines := _source_lines(output, s, lang)):
                extra.append(
                    f"{SOURCES[s].split(' / ')[0 if lang == 'zh' else -1]}:\n" + _format(lines, "bullet_list")
                )
        if extra:
            last = rendered[-1]
            last[2] = "\n\n".join(p for p in [last[2], *extra] if p)
    return [content(i, key, text) for i, key, text in rendered]
