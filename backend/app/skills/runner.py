"""SkillRunner: the single entry point for running anything through the LLM.

inputs -> role check -> pre-rules -> context providers (via Relay) -> prompt assembly
       -> tool loop -> JSON parse -> schema check + post-rules
       -> (one retry with the errors as feedback) -> code-owned overlay
       -> Markdown render -> skill_runs record
"""

