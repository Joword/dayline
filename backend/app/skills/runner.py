log = logging.getLogger("dayline.skills")

_FENCE_RE = re.compile(r"^```(?:json)?\s*(.*?)\s*```$", re.DOTALL)

NOTICES = {
    "zh": {"degraded": "本结果由备用模型生成。", "review": "请人工复核后再使用。"},
    "en": {"degraded": "Generated by a backup model.", "review": "Please review before using it."},
}

FEEDBACK = {
    "zh": "你上一次的输出没有通过校验,问题如下:\n{errors}\n请修正这些问题,重新输出完整的结果。",
    "en": "Your previous output failed validation:\n{errors}\nFix these problems and output the complete result again.",
}


class SkillInputError(ValueError):
    pass


class SkillForbidden(PermissionError):
    pass


class SkillRunError(RuntimeError):
    def __init__(self, msg: str, *, run_id: str, status: str):
        super().__init__(msg)
        self.run_id = run_id
        self.status = status


class SkillRunResult(BaseModel):
    run_id: str
    skill: str
    version: str
    lang: str
    status: Literal["ok", "invalid"]
    output: Any = None
    markdown: str = ""
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    notice: str | None = None
    failover: bool = False
    degraded: bool = False
    endpoint: str | None = None
    model: str | None = None
    usage: Usage = Field(default_factory=Usage)
    cost_usd: float | None = None
    latency_ms: int = 0
    validation_attempts: int = 1
    # per context provider: values for the caller (e.g. the reviewed report's id)
    context: dict[str, Any] = Field(default_factory=dict)


def _unavailable(reason: str) -> dict[str, Any]:
    return {"available": False, "reason": reason}


def extract_json(text: str) -> Any:
    t = text.strip()
    if m := _FENCE_RE.match(t):
        t = m.group(1)
    try:
        return json.loads(t)
    except ValueError:
        # tolerate prose around the object on endpoints without constrained decoding
        start, end = t.find("{"), t.rfind("}")
        if start != -1 and end > start:
            return json.loads(t[start : end + 1])
        raise


class SkillRunner:
    def __init__(
        self,
        *,
        registry: SkillRegistry,
        gateway: LLMGateway,
        tools: ToolRegistry,
        rules: RuleEngine,
        runs_repo: Any = None,
        relay: Relay | None = None,
        default_lang: str = "zh",
        timezone: str = "Asia/Shanghai",
        trace_max_bytes: int = 64_000,
    ):
        self.registry = registry
        self.gateway = gateway
        self.tools = tools
        self.rules = rules
        self.runs_repo = runs_repo
        self.relay = relay
        self.providers = providers()
        self.default_lang = default_lang
        self.tz = ZoneInfo(timezone)
        self.trace_max_bytes = trace_max_bytes

    def today(self) -> date:
        return datetime.now(self.tz).date()

    async def run(
        self,
        name: str,
        inputs: dict[str, Any],
        *,
        user_id: str,
        lang: str | None = None,
        client_id: str = "dayline",
        context_override: dict[str, Any] | None = None,
    ) -> SkillRunResult:
        """``context_override`` replays recorded provider data instead of reading the
        database, and skips the role check. Evals and tests only - never wire it to
        user input (the API and CLI do not pass it)."""
        skill = self.registry.get(name)
        m = skill.manifest
        lang = lang or self.default_lang
        if lang not in ("zh", "en"):
            raise SkillInputError(f"unsupported language: {lang}")
        try:
            values = coerce_inputs(m.inputs, inputs, today=self.today())
        except ValueError as e:
            raise SkillInputError(str(e)) from e
        rctx = RuleContext(skill=m.name, lang=lang, inputs=values)
        pre = self.rules.run(m.rules, "pre", values, rctx)
        if errs := [f for f in pre if f.level == "error"]:
            raise SkillInputError("; ".join(map(str, errs)))

        run_date = str(values.get("date") or self.today().isoformat())
        viewer = None
        if self.relay is not None:
            try:
                viewer = await self.relay.viewer(user_id, client_id=client_id)
            except RelayNotFound:
                viewer = None  # not in the org: fine for skills that need no org data
        if context_override is None and "member" not in m.roles:
            if viewer is None or not await self.relay.is_manager(user_id):  # type: ignore[union-attr]
                raise SkillForbidden(f"skill '{m.name}' is for managers with direct reports")

        context, overlay, meta = await self._context(
            skill, values, viewer, run_date, lang, rctx, override=context_override
        )

        run_id = uuid.uuid4().hex
        token = skill_run_id_var.set(run_id)
        try:
            return await self._run(
                skill, values, lang, user_id, run_id, run_date, rctx, viewer, context, overlay, meta
            )
        finally:
            skill_run_id_var.reset(token)

    async def _context(
        self,
        skill: Skill,
        values: dict[str, Any],
        viewer: Any,
        run_date: str,
        lang: str,
        rctx: RuleContext,
        *,
        override: dict[str, Any] | None = None,
    ) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
        context: dict[str, Any] = {}
        overlay: dict[str, Any] = {}
        meta: dict[str, Any] = {}
        quotes: list[str] = []
        for spec in skill.manifest.context:
            provider = self.providers[spec.name]
            if override is not None:
                if spec.name in override:
                    res = provider.replay(override[spec.name])
                elif spec.optional:
                    res = provider.replay(_unavailable("not provided"))
                else:
                    raise SkillInputError(f"context override is missing '{spec.name}'")
            elif viewer is None:
                if not spec.optional:
                    raise SkillForbidden(
                        f"skill '{skill.name}' needs report storage and a user that exists in the org"
                    )
                res = provider.replay(_unavailable("no report storage, or the user is not in the org"))
            else:
                req = ContextRequest(
                    relay=self.relay,
                    viewer=viewer,
                    inputs=values,
                    params=spec.params,
                    run_date=run_date,
                    lang=lang,
                )
                try:
                    res = await provider.fn(req)
                except (RelayForbidden, RelayNotFound) as e:
                    if spec.optional:
                        res = provider.replay(_unavailable(str(e)))
                    elif isinstance(e, RelayForbidden):
                        raise SkillForbidden(str(e)) from e
                    else:
                        raise SkillInputError(str(e)) from e
            context[spec.name] = res.data
            overlay.update(res.overlay or {})
            meta[spec.name] = res.meta
            if res.quote_source:
                quotes.append(res.quote_source)
        rctx.extras.update(quote_source="\n".join(quotes) or None, context_meta=meta)
        return context, overlay, meta

    async def _run(
        self,
        skill: Skill,
        values: dict[str, Any],
        lang: str,
        user_id: str,
        run_id: str,
        run_date: str,
        rctx: RuleContext,
        viewer: Any,
        context: dict[str, Any],
        overlay: dict[str, Any],
        meta: dict[str, Any],
    ) -> SkillRunResult:
        m = skill.manifest
        req = build_request(skill, values, lang=lang, run_date=run_date, context=context)
        tctx = ToolContext(
            user_id=user_id,
            lang=lang,
            date=date.fromisoformat(run_date),
            relay=self.relay if viewer is not None else None,
            viewer=viewer,
            extras={"run_id": run_id},
        )
        allowed, tool_warnings = await self.tools.for_run(m.tools, user_id=user_id, permissions=m.permissions)
        loops: list[LoopResult] = []
        doc = SkillRunDoc(
            run_id=run_id, skill=m.name, version=m.version, user_id=user_id, lang=lang, status="error"
        )

        try:
            res = await run_tool_loop(
                self.gateway,
                req,
                tools=self.tools,
                allowed=allowed,
                ctx=tctx,
                max_tool_turns=m.max_tool_turns,
            )
            loops.append(res)
            output, errors, warnings = self._check(skill, res.response.text, rctx)
            if errors:
                log.info(
                    "skill output failed validation; retrying once", extra={"skill": m.name, "errors": errors}
                )
                feedback = FEEDBACK[lang].format(errors="\n".join(f"- {e}" for e in errors))
                retry_req = req.model_copy(update={"messages": [*res.messages, Message.user(feedback)]})
                res = await run_tool_loop(
                    self.gateway, retry_req, tools=self.tools, allowed=allowed, ctx=tctx, max_tool_turns=0
                )
                loops.append(res)
                output, errors, warnings = self._check(skill, res.response.text, rctx)
        except RefusalError as e:
            doc.status, doc.error = "refused", str(e)
            await self._record(doc, loops)
            raise SkillRunError(
                "模型拒绝了该请求" if lang == "zh" else "the model declined this request",
                run_id=run_id,
                status="refused",
            ) from e
        except LLMError as e:
            doc.status, doc.error = "error", str(e)
            await self._record(doc, loops)
            raise SkillRunError(str(e), run_id=run_id, status="error") from e

        warnings = tool_warnings + warnings
        last = loops[-1]
        degraded = any(lp.degraded for lp in loops)
        notice = None
        if degraded:
            notice = NOTICES[lang]["degraded"] + (
                " " + NOTICES[lang]["review"] if m.review_on_fallback else ""
            )
        if not errors and overlay and isinstance(output, dict):
            output = {**output, **overlay}  # code-owned fields win over anything the model wrote
        markdown = render_markdown(m.output.template, output, lang) if not errors else ""
        result = SkillRunResult(
            run_id=run_id,
            skill=m.name,
            version=m.version,
            lang=lang,
            status="invalid" if errors else "ok",
            output=output,
            markdown=markdown,
            errors=errors,
            warnings=warnings,
            notice=notice,
            failover=any(lp.failover for lp in loops),
            degraded=degraded,
            endpoint=last.response.endpoint,
            model=last.response.model,
            usage=sum((lp.usage for lp in loops), Usage()),
            cost_usd=_sum_cost(loops),
            latency_ms=sum(lp.latency_ms for lp in loops),
            validation_attempts=len(loops),
            context=meta,
        )
        doc.status = result.status
        doc.error = "; ".join(errors) or None
        doc.warnings = warnings
        await self._record(doc, loops)
        return result

    def _check(self, skill: Skill, text: str, rctx: RuleContext) -> tuple[Any, list[str], list[str]]:
        m = skill.manifest
        if skill.output_schema is None:
            post = self.rules.run(m.rules, "post", {"text": text}, rctx)
            return (
                text,
                [str(f) for f in post if f.level == "error"],
                [str(f) for f in post if f.level == "warning"],
            )
        try:
            data = extract_json(text)
        except ValueError:
            return text, ["output is not valid JSON"], []
        data, errors = skill.validate_output(data)
        if errors:
            return data, errors, []
        post = self.rules.run(m.rules, "post", data, rctx)
        return (
            data,
            [str(f) for f in post if f.level == "error"],
            [str(f) for f in post if f.level == "warning"],
        )

    async def _record(self, doc: SkillRunDoc, loops: list[LoopResult]) -> None:
        if loops:
            last = loops[-1]
            usage = sum((lp.usage for lp in loops), Usage())
            doc.endpoint = last.response.endpoint
            doc.endpoints = list(dict.fromkeys(e for lp in loops for e in lp.endpoints))
            doc.model = last.response.model
            doc.failover = any(lp.failover for lp in loops)
            doc.degraded = any(lp.degraded for lp in loops)
            doc.tokens_in, doc.tokens_out = usage.input_tokens, usage.output_tokens
            doc.cache_read_tokens, doc.cache_write_tokens = usage.cache_read_tokens, usage.cache_write_tokens
            doc.cost = _sum_cost(loops)
            doc.latency_ms = sum(lp.latency_ms for lp in loops)
            doc.validation_attempts = len(loops)
            trace = [t.model_dump() for lp in loops for t in lp.trace]
            raw = json.dumps(trace, ensure_ascii=False, default=str)
            if len(raw.encode()) > self.trace_max_bytes:
                doc.trace = [
                    {k: t[k] for k in ("endpoint", "model", "stop_reason", "latency_ms")} for t in trace
                ]
                doc.trace_truncated = True
            else:
                doc.trace = trace
        log.info(
            "skill run finished",
            extra={"skill": doc.skill, "status": doc.status, "cost": doc.cost, "latency_ms": doc.latency_ms},
        )
        if self.runs_repo is None:
            return
        try:
            await self.runs_repo.record(doc)
        except Exception:  # observability must not break the user's run
            log.exception("failed to record skill run")


def _sum_cost(loops: list[LoopResult]) -> float | None:
    costs = [lp.cost_usd for lp in loops if lp.cost_usd is not None]
    return round(sum(costs), 6) if costs else None
